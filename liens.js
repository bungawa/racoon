/* References become links. Whatever names a page of the site is clickable, in every text, even text inserted later
   (quiz feedback, épreuve results). Convention (design-system/rediger-une-lecon.md):
   - a title between guillemets, exactly as written: « Frottements » → its lesson; the word before chooses among
     same-titled pages (« leçon », « étape », « article », « notion »), else lesson, then article, then step.
     A notion (/atlas?notion=<id>) is linked only after the word « notion ».
   - an equation number (12.7) → its anchor: on this page if it is here, else the one lesson that holds it,
     else the one of the page's step, else the one of the same Feynman volume and chapter,
     else nothing. A number held by several pages is cited with its page: « (12.7) de « Titre » » goes to that page, and so do both numbers of « (12.7) et (12.8) de « Titre » ». Feynman's numbers are keys, never shown: each page numbers its
     equations 1, 2, 3; a citation reads « (3) » on its page, « (3) de « Titre » » from another.
   Never linked: the page itself, text already in a link, buttons, drawings, formulas, code, the <h1>, the crumb,
   the footer (sources are cited, never linked), equation labels.
   Index: /liens.json, generated by tools/liens-index.js from the lesson lists, the parcours and the pages.
   Pure core: titres(), plan(); DOM: watch(). */
(function (root) {
  const SKIP = "script,style,a,button,svg,math,code,h1,.crumb,.eq,.foot,title,select,option,textarea,[popover],.sigles,.no-lien";
  const KEEP = "script,style,math,code,.eq,.foot,textarea";        // where a Feynman number is text, not a citation
  const BLOCK = "p,li,dd,dt,td,th,figcaption,h2,h3,h4,blockquote,div,section,main";
  const KIND = { lecon: /^le[çc]ons?$/i, etape: /^[ée]tapes?$/i, article: /^articles?$/i, notion: /^notions?$/i };
  const ORDER = ["lecon", "article", "etape"];                     // a notion needs its word
  const EQ = /\((\d+\.\d+[a-z]?′?)\)/gu;
  const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const clean = s => String(s == null ? "" : s).replace(/[⟦⟧]/g, "").trim();
  const norm = s => clean(s).replace(/\s+/g, " ").replace(/’/g, "'");

  /* "12.7" → "eq-12-7" ; the label of an equation "(11.15–11.16)" → its numbers */
  const anchor = n => "eq-" + String(n).replace(/\./g, "-").replace(/′/g, "p");
  const numbers = label => {                                // (25.14–15) is (25.14) and (25.15) ; (23.14–16) also (23.15)
    const ps = clean(label).replace(/^\(|\)$/g, "").split(/[–-]/).map(s => s.trim()), ch = (ps[0].match(/^(\d+)\./) || [])[1];
    const ns = ps.map(s => ch && /^\d+[a-z]?′?$/u.test(s) ? ch + "." + s : s).filter(s => /^\d+\.\d+[a-z]?′?$/u.test(s));
    const [a, b] = ns.map(n => n.match(/^(\d+)\.(\d+)$/));
    if (ns.length !== 2 || !a || !b || a[1] !== b[1] || +b[2] <= +a[2] + 1 || +b[2] - +a[2] > 9) return ns;
    return Array.from({ length: b[2] - a[2] + 1 }, (_, i) => a[1] + "." + (+a[2] + i));
  };

  /* index → {re, by}: the guillemet pattern of every title, and its targets by normalised title */
  function titres(index, pick) {
    pick = pick || (x => x == null || typeof x !== "object" ? x : x.fr);
    const by = new Map();
    (index.titres || []).forEach(t => {
      const k = norm(pick(t.titre));
      if (!k) return;
      if (!by.has(k)) by.set(k, []);
      by.get(k).push({ kind: t.kind, href: t.href });
    });
    const of = new Map((index.titres || []).filter(t => t.kind === "lecon" || t.kind === "article").map(t => [t.href, clean(pick(t.titre))]));
    const keys = [...by.keys()].sort((a, b) => b.length - a.length);
    const pat = k => esc(k).replace(/'/g, "['’]").replace(/ /g, "\\s+");
    const re = keys.length ? new RegExp("«\\s*(" + keys.map(pat).join("|") + ")\\s*»", "gu") : null;
    return { re, by, of };
  }

  /* the kind named by the last « leçon(s) / étape(s) / article(s) / notion(s) » of the sentence before a title */
  function motCle(before) {
    const s = before.split(/[.!?](?=\s|$)/).pop(), words = s.match(/[\p{L}]+/gu) || [];
    for (let i = words.length - 1; i >= 0; i--) for (const k in KIND) if (KIND[k].test(words[i])) return k;
    return null;
  }
  function cible(list, kind, here) {
    const ok = list.filter(t => t.href !== here);
    if (kind) { const k = ok.find(t => t.kind === kind); if (k) return k.href; }
    if (list.some(t => t.href === here && t.kind !== "notion") && !kind) return null;   // the page names itself
    for (const k of ORDER) { const t = ok.find(x => x.kind === k); if (t) return t.href; }
    return null;
  }
  /* the pages named right after a citation, « (12.7) de « Titre » » (after: the text that follows it), or null */
  const NOMME = /^(?:\s*(?:,|et|ou)\s*\(\d+\.\d+[a-z]?′?\))*,?\s+de\s+(?:la\s+le[çc]on\s+|l['’]article\s+)?«\s*([^»]+?)\s*»/u;
  function nommees(after, T) {
    const m = T && T.by && after && after.match(NOMME), list = m && T.by.get(norm(m[1]));
    return list ? list.map(t => t.href) : null;
  }
  /* equation n seen from page here → href, or null when unknown or ambiguous */
  function equation(index, n, here, after, T) { const c = cite(index, n, here, after, T); return c && c.href; }
  /* … and its target [page, anchor, k]; named: the text names its page */
  function cite(index, n, here, after, T) {
    const h = (index.equations || {})[n];
    if (!h || !h.length) return null;
    const to = x => ({ href: x[0] === here ? "#" + x[1] : x[0] + "#" + x[1], page: x[0], k: x[2] });
    const named = nommees(after, T);
    if (named) { const x = h.find(e => named.includes(e[0])); return x ? { ...to(x), named: true } : null; }
    const mine = h.find(x => x[0] === here);
    if (mine) return to(mine);
    const step = here.startsWith("/racoon/etape?id=") ? here.slice(10) : (index.etapes || {})[here];
    const same = step ? h.filter(x => (index.etapes || {})[x[0]] === step) : [];
    if (same.length === 1) return to(same[0]);
    /* Feynman numbers (6.1) in chapter 6 of each volume: from a page of volume II, the lesson of II.6 */
    const S = index.sections || {}, vol = c => (S[c] || "").split(".")[0], chap = c => (S[c] || "").split(".")[1];
    const v = vol(here), ch = String(n).split(".")[0];
    const fey = v && v !== "X" ? h.filter(x => vol(x[0]) === v && chap(x[0]) === ch) : [];
    if (fey.length === 1) return to(fey[0]);
    /* the only page holding the number, unless it is another volume of Feynman: (8.8) of II.8 is not (8.8) of I.8 */
    const autre = x => v && v !== "X" && vol(x[0]) && vol(x[0]) !== "X" && vol(x[0]) !== v;
    return h.length === 1 && !autre(h[0]) ? to(h[0]) : null;
  }

  /* what a citation shows: « (3) » on its page, « (3) de « Titre » » from another (title: T.of, by href) */
  const shown = (c, here, T) => "(" + c.k + ")" + (c.page === here || c.named ? "" : " de « " + ((T.of && T.of.get(c.page)) || "") + " »");

  /* text: one text node; before: the text of its block before it; T = titres(index); here: this page's href.
     → [{at, len, href, text?}] in order, without overlap; at/len cover the title (not its guillemets) or the whole
     « (n.m) », replaced by text. */
  function plan(text, before, T, index, here) {
    const out = [];
    if (T.re) for (const m of text.matchAll(T.re)) {
      const at = m.index + m[0].indexOf(m[1]), list = T.by.get(norm(m[1]));
      const href = list && cible(list, motCle(before + text.slice(0, m.index)), here);
      if (href) out.push({ at, len: m[1].length, href });
    }
    for (const m of text.matchAll(EQ)) {
      const c = cite(index, m[1], here, text.slice(m.index + m[0].length), T);
      if (c && !out.some(o => m.index < o.at + o.len && o.at < m.index + m[0].length)) out.push({ at: m.index, len: m[0].length, href: c.href, text: shown(c, here, T) });
    }
    return out.sort((a, b) => a.at - b.at);
  }

  /* this page's href, as the index writes it */
  function ici(loc) {
    const p = loc.pathname.replace(/\.html$/, "").replace(/\/index$/, "/").replace(/(.)\/$/, "$1");
    if (p === "/racoon/etape") return "/racoon/etape?id=" + (new URLSearchParams(loc.search).get("id") || "");
    return p;
  }

  /* ---------- DOM ---------- */
  function ancres(main) {                                 // every numbered equation: its anchor, and its number on the page
    let k = 0;
    main.querySelectorAll(".eq").forEach(eq => {
      const n = eq.querySelector(".n");
      if (!n) return;
      if (!n.dataset.n) n.dataset.n = n.textContent;
      const ns = numbers(n.dataset.n);
      if (!ns.length) return;
      k++; if (!eq.id) eq.id = anchor(ns[0]);
      if (n.textContent !== "(" + k + ")") n.textContent = "(" + k + ")";
    });
  }
  function apply(main, T, index, here) {
    const doc = main.ownerDocument, w = doc.createTreeWalker(main, NodeFilter.SHOW_TEXT), seen = new Map(), todo = [];
    for (let n = w.nextNode(); n; n = w.nextNode()) {
      const p = n.parentElement;
      if (!p || p.closest("script,style")) continue;
      const b = p.closest(BLOCK) || main, before = seen.get(b) || "";
      seen.set(b, before + n.nodeValue);
      if (p.closest(SKIP)) {                                  // no link here (a quiz button…), but the number is the page's
        if (!p.closest(KEEP)) { const t = n.nodeValue.replace(EQ, (all, x, at, s) => { const c = cite(index, x, here, s.slice(at + all.length), T); return c ? shown(c, here, T) : all; }); if (t !== n.nodeValue) n.nodeValue = t; }
        continue;
      }
      const plan_ = plan(n.nodeValue, before, T, index, here);
      if (plan_.length) todo.push([n, plan_]);
    }
    todo.forEach(([n, ps]) => {
      for (let i = ps.length - 1; i >= 0; i--) {             // from the end: earlier offsets stay valid
        const { at, len, href, text } = ps[i], mid = n.splitText(at);
        mid.splitText(len);
        const a = doc.createElement("a");
        a.href = href; a.textContent = text || mid.nodeValue;
        mid.replaceWith(a);
      }
    });
    return todo.length;
  }
  let data = null;
  function load() { return data || (data = fetch("/racoon/liens.json").then(r => r.ok ? r.json() : null).catch(() => null)); }

  /* I: the page's I18n instance (pick reads the display language). Re-applies when the page changes. */
  function watch(main, I) {
    if (!main) return;
    ancres(main);
    const here = ici(location);
    load().then(index => {
      if (!index) return;
      const T = titres(index, x => clean(I && I.pick ? I.pick(x) : x));
      let queued = false;
      const run = () => {
        queued = false; obs.disconnect();
        ancres(main); apply(main, T, index, here);
        obs.observe(main, { subtree: true, childList: true, characterData: true });
        document.documentElement.dataset.liens = "ok";
      };
      const obs = new MutationObserver(() => { if (!queued) { queued = true; queueMicrotask(run); } });
      run();
      const h = location.hash && document.getElementById(decodeURIComponent(location.hash.slice(1)));
      if (h && !h.dataset.vu) { h.dataset.vu = "1"; h.scrollIntoView(); }
    });
  }

  const api = { SKIP, EQ, anchor, numbers, titres, motCle, cible, equation, cite, shown, plan, ici, watch };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  else root.Liens = api;
})(typeof self !== "undefined" ? self : this);
